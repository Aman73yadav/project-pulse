-- ============ visibility helpers ============
CREATE OR REPLACE FUNCTION public.can_view_project(_project_id uuid)
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT public.is_admin()
    OR EXISTS (SELECT 1 FROM public.projects p WHERE p.id = _project_id AND p.created_by = auth.uid())
    OR EXISTS (SELECT 1 FROM public.tasks t WHERE t.project_id = _project_id AND t.assignee_id = auth.uid());
$$;

CREATE OR REPLACE FUNCTION public.can_manage_project(_project_id uuid)
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT public.is_admin()
    OR EXISTS (SELECT 1 FROM public.projects p WHERE p.id = _project_id AND p.created_by = auth.uid());
$$;

CREATE OR REPLACE FUNCTION public.can_view_task(_task_id uuid)
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT EXISTS (
    SELECT 1 FROM public.tasks t
    WHERE t.id = _task_id
      AND (t.assignee_id = auth.uid() OR public.can_manage_project(t.project_id))
  );
$$;

-- ============ policies ============
CREATE POLICY "profiles readable by signed-in team" ON public.profiles
  FOR SELECT TO authenticated USING (true);
CREATE POLICY "insert own profile" ON public.profiles
  FOR INSERT TO authenticated WITH CHECK (id = auth.uid());
CREATE POLICY "update own profile" ON public.profiles
  FOR UPDATE TO authenticated USING (id = auth.uid()) WITH CHECK (id = auth.uid());

CREATE POLICY "roles readable by signed-in team" ON public.user_roles
  FOR SELECT TO authenticated USING (true);

CREATE POLICY "clients visible to managers" ON public.clients
  FOR SELECT TO authenticated USING (public.is_manager());
CREATE POLICY "admins insert clients" ON public.clients
  FOR INSERT TO authenticated WITH CHECK (public.is_admin());
CREATE POLICY "admins update clients" ON public.clients
  FOR UPDATE TO authenticated USING (public.is_admin()) WITH CHECK (public.is_admin());
CREATE POLICY "admins delete clients" ON public.clients
  FOR DELETE TO authenticated USING (public.is_admin());

CREATE POLICY "projects visible to owner admin or assignee" ON public.projects
  FOR SELECT TO authenticated USING (public.can_view_project(id));
CREATE POLICY "managers create own projects" ON public.projects
  FOR INSERT TO authenticated WITH CHECK (public.is_manager() AND created_by = auth.uid());
CREATE POLICY "owners update projects" ON public.projects
  FOR UPDATE TO authenticated USING (public.can_manage_project(id)) WITH CHECK (public.can_manage_project(id));
CREATE POLICY "owners delete projects" ON public.projects
  FOR DELETE TO authenticated USING (public.can_manage_project(id));

CREATE POLICY "tasks visible to assignee or project manager" ON public.tasks
  FOR SELECT TO authenticated USING (assignee_id = auth.uid() OR public.can_manage_project(project_id));
CREATE POLICY "project owners create tasks" ON public.tasks
  FOR INSERT TO authenticated WITH CHECK (public.can_manage_project(project_id));
CREATE POLICY "owners or assignee update tasks" ON public.tasks
  FOR UPDATE TO authenticated
  USING (public.can_manage_project(project_id) OR assignee_id = auth.uid())
  WITH CHECK (public.can_manage_project(project_id) OR assignee_id = auth.uid());
CREATE POLICY "owners delete tasks" ON public.tasks
  FOR DELETE TO authenticated USING (public.can_manage_project(project_id));

CREATE POLICY "activity visible by task or project scope" ON public.task_activity
  FOR SELECT TO authenticated
  USING (public.can_manage_project(project_id) OR (task_id IS NOT NULL AND public.can_view_task(task_id)));
CREATE POLICY "activity insert by actor" ON public.task_activity
  FOR INSERT TO authenticated WITH CHECK (actor_id = auth.uid());

CREATE POLICY "own notifications" ON public.notifications
  FOR SELECT TO authenticated USING (recipient_id = auth.uid());
CREATE POLICY "update own notifications" ON public.notifications
  FOR UPDATE TO authenticated USING (recipient_id = auth.uid()) WITH CHECK (recipient_id = auth.uid());

-- ============ column-level guard: developers may only move status ============
CREATE OR REPLACE FUNCTION public.guard_task_update()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  NEW.updated_at := now();
  IF auth.uid() IS NOT NULL AND NOT public.can_manage_project(NEW.project_id) THEN
    IF NEW.title <> OLD.title
       OR COALESCE(NEW.description,'') <> COALESCE(OLD.description,'')
       OR COALESCE(NEW.assignee_id, '00000000-0000-0000-0000-000000000000') <> COALESCE(OLD.assignee_id, '00000000-0000-0000-0000-000000000000')
       OR NEW.priority <> OLD.priority
       OR COALESCE(NEW.due_date, 'epoch'::timestamptz) <> COALESCE(OLD.due_date, 'epoch'::timestamptz)
       OR NEW.project_id <> OLD.project_id THEN
      RAISE EXCEPTION 'Developers may only change task status';
    END IF;
  END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER trg_guard_task_update BEFORE UPDATE ON public.tasks
  FOR EACH ROW EXECUTE FUNCTION public.guard_task_update();

-- ============ activity + notification triggers ============
CREATE OR REPLACE FUNCTION public.log_task_insert()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE actor uuid := COALESCE(auth.uid(), NEW.created_by);
BEGIN
  INSERT INTO public.task_activity (task_id, project_id, actor_id, action, to_status, detail)
  VALUES (NEW.id, NEW.project_id, actor, 'created', NEW.status, NEW.title);

  IF NEW.assignee_id IS NOT NULL THEN
    INSERT INTO public.task_activity (task_id, project_id, actor_id, action, detail)
    VALUES (NEW.id, NEW.project_id, actor, 'assigned', NEW.title);
    INSERT INTO public.notifications (recipient_id, type, task_id, project_id, message)
    VALUES (NEW.assignee_id, 'task_assigned', NEW.id, NEW.project_id,
            'You were assigned Task #' || NEW.task_number || ': ' || NEW.title);
  END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER trg_log_task_insert AFTER INSERT ON public.tasks
  FOR EACH ROW EXECUTE FUNCTION public.log_task_insert();

CREATE OR REPLACE FUNCTION public.log_task_update()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  actor uuid := auth.uid();
  pm uuid;
BEGIN
  IF NEW.status IS DISTINCT FROM OLD.status THEN
    INSERT INTO public.task_activity (task_id, project_id, actor_id, action, from_status, to_status, detail)
    VALUES (NEW.id, NEW.project_id, actor, 'status_changed', OLD.status, NEW.status, NEW.title);

    IF NEW.status = 'in_review' THEN
      SELECT created_by INTO pm FROM public.projects WHERE id = NEW.project_id;
      IF pm IS NOT NULL AND pm IS DISTINCT FROM actor THEN
        INSERT INTO public.notifications (recipient_id, type, task_id, project_id, message)
        VALUES (pm, 'task_in_review', NEW.id, NEW.project_id,
                'Task #' || NEW.task_number || ' is ready for review: ' || NEW.title);
      END IF;
    END IF;
  END IF;

  IF NEW.assignee_id IS DISTINCT FROM OLD.assignee_id AND NEW.assignee_id IS NOT NULL THEN
    INSERT INTO public.task_activity (task_id, project_id, actor_id, action, detail)
    VALUES (NEW.id, NEW.project_id, actor, 'assigned', NEW.title);
    INSERT INTO public.notifications (recipient_id, type, task_id, project_id, message)
    VALUES (NEW.assignee_id, 'task_assigned', NEW.id, NEW.project_id,
            'You were assigned Task #' || NEW.task_number || ': ' || NEW.title);
  END IF;

  IF NEW.is_overdue AND NOT OLD.is_overdue THEN
    INSERT INTO public.task_activity (task_id, project_id, actor_id, action, detail)
    VALUES (NEW.id, NEW.project_id, NULL, 'flagged_overdue', NEW.title);
  END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER trg_log_task_update AFTER UPDATE ON public.tasks
  FOR EACH ROW EXECUTE FUNCTION public.log_task_update();

-- ============ overdue sweeper (scheduled) ============
CREATE OR REPLACE FUNCTION public.flag_overdue_tasks()
RETURNS integer LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE flagged integer;
BEGIN
  WITH upd AS (
    UPDATE public.tasks
    SET is_overdue = true
    WHERE is_overdue = false
      AND status <> 'done'
      AND due_date IS NOT NULL
      AND due_date < now()
    RETURNING 1
  ) SELECT count(*) INTO flagged FROM upd;

  UPDATE public.tasks SET is_overdue = false
  WHERE is_overdue = true AND (status = 'done' OR due_date IS NULL OR due_date >= now());

  RETURN flagged;
END;
$$;
REVOKE ALL ON FUNCTION public.flag_overdue_tasks() FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.flag_overdue_tasks() TO service_role;

